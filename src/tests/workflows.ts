import assert from 'node:assert/strict';
import { createDemo } from '../services/demo';
import { saveProduct, changeStock } from '../services/inventory';
import { cartLines, filterSales, integer, largeChange, money, stockStatus, summary } from '../services/calculations';
import { recordSale } from '../services/sales';
import { createRepository, type LocalStorageAdapter } from '../services/repository';

async function check() {
  let db = createDemo();
  assert.ok(db.products.some(p => stockStatus(p) === 'Out of stock'));
  assert.ok(db.products.some(p => stockStatus(p) === 'Low stock'));
  assert.equal(summary(db.sales).profit, null);
  assert.equal(summary(db.sales).incomplete, true);
  assert.equal(summary(filterSales(db.sales, 'today')).incomplete, false);
  assert.equal(money(1500), '1,500 XAF');
  assert.ok(Number.isNaN(integer('1.5'))); assert.ok(Number.isNaN(integer('-1'))); assert.ok(Number.isNaN(integer('')));
  assert.ok(largeChange(100, 1));
  const input = { name: 'Test product', category: 'Pantry', price: 1500, cost: 1000, quantity: 5, threshold: 3, sku: 'TEST-123' };
  const added = saveProduct(db, input); db = added.db; const id = added.id;
  assert.equal(db.movements.at(-1)?.reason, 'Opening stock');
  assert.throws(() => saveProduct(db, { ...input, name: ' TEST PRODUCT ' }), /already exists/);
  assert.throws(() => saveProduct(db, { ...input, name: '' }), /name/);
  assert.throws(() => saveProduct(db, { ...input, name: 'another', price: 0 }), /Selling price/);
  assert.throws(() => saveProduct(db, { ...input, name: 'another', quantity: 1.5 }), /Stock quantity/);
  db = changeStock(db, id, 8, 'Delivery', 'Supplier A', 5, 1100);
  assert.equal(db.products.find(p => p.id === id)?.quantity, 13);
  assert.equal(db.products.find(p => p.id === id)?.cost, 1100);
  assert.throws(() => changeStock(db, id, 1, 'Delivery', '', 5), /Stock changed/);
  db = changeStock(db, id, -2, 'Damaged / expired', 'Damaged', 13);
  db = changeStock(db, id, 1, 'Customer return', 'Resellable', 11);
  db = changeStock(db, id, -2, 'Count correction', 'Counted ten', 12);
  assert.equal(db.products.find(p => p.id === id)?.quantity, 10);
  assert.throws(() => changeStock(db, id, -11, 'Damaged / expired', '', 10), /Resulting quantity/);
  assert.throws(() => changeStock(db, id, -1, 'Delivery', '', 10), /adds stock/);
  const cart = { [id]: 3 }; const reviewed = cartLines(db.products, cart);
  const result = recordSale(db, cart, 'Mobile money', reviewed); db = result.db;
  assert.equal(db.products.find(p => p.id === id)?.quantity, 7);
  assert.equal(result.sale.total, 4500); assert.equal(summary([result.sale]).profit, 1200);
  assert.equal(db.movements.at(-1)?.saleId, result.sale.id);
  assert.equal(db.sales.find(s => s.id === result.sale.id)?.receiptNumber, result.sale.receiptNumber);
  assert.equal(new Set(db.sales.map(s => s.receiptNumber)).size, db.sales.length);
  assert.throws(() => cartLines(db.products, { [id]: 8 }), /only 7/);
  const edited = saveProduct(db, { ...input, quantity: 7, price: 2000, cost: 1500 }, id).db;
  assert.equal(edited.sales[0].lines[0].unitPrice, 1500);
  assert.equal(edited.sales[0].lines[0].unitCost, 1100);
  assert.throws(() => recordSale(edited, cart, 'Cash', reviewed), /changed/);
  const unknownCost = saveProduct(edited, { ...input, name: 'No cost item', quantity: 1, cost: null });
  const unknownCart = { [unknownCost.id]: 1 };
  const unknown = recordSale(unknownCost.db, unknownCart, 'Cash', cartLines(unknownCost.db.products, unknownCart));
  assert.equal(summary([unknown.sale]).profit, null);
  const remaining = cartLines(edited.products, { [id]: 7 });
  const empty = recordSale(edited, { [id]: 7 }, 'Cash', remaining);
  assert.equal(stockStatus(empty.db.products.find(p => p.id === id)!), 'Out of stock');
  for (const p of db.products) {
    const movements = db.movements.filter(m => m.productId === p.id);
    let running = 0;
    for (const m of movements) { running += m.delta; assert.equal(running, m.resultingQuantity); assert.ok(running >= 0); }
    assert.equal(running, p.quantity);
  }
  assert.equal(db.products.filter(p => `${p.name} ${p.sku}`.toLowerCase().includes('test-123')).length, 1);
  assert.deepEqual(filterSales([], 'all'), []);
  assert.equal(summary([]).profit, 0);
  const original = JSON.stringify(db); let saved = original; let fail = false;
  const storage: LocalStorageAdapter = { async getItem() { return saved; }, async setItem(_key, value) { if (fail) throw new Error('Disk full'); saved = value; } };
  const repo = createRepository(storage); await repo.load();
  fail = true;
  await assert.rejects(repo.transact(current => ({ db: { ...current, shop: { ...current.shop, name: 'Failed write' } }, result: null })), /Disk full/);
  assert.equal(saved, original);
  fail = false;
  const commits = await Promise.all([repo.transact(current => ({ db: changeStock(current, id, 1, 'Delivery', '', 7), result: null })), repo.transact(current => ({ db: changeStock(current, id, 1, 'Delivery', '', 8), result: null }))]);
  assert.equal(commits[1].db.products.find(p => p.id === id)?.quantity, 9);
  const reloaded = await createRepository(storage).load();
  assert.equal(reloaded.products.find(p => p.id === id)?.quantity, 9);
  saved = '{bad json';
  await assert.rejects(createRepository(storage).load());
  assert.equal(saved, '{bad json');
  console.log('PASS: add → receive → damage → return → correct → sell → receipt; duplicate/invalid inputs; stock limits; integer totals; cost snapshots; filters; movement consistency; serialized persistence; failed-write safety; reload; corrupt-data protection.');
}
check().catch(error => { console.error(error); process.exitCode = 1; });
